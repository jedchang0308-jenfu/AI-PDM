#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const sourcePath = path.join(root, "docs", "pdm-management-policy-draft.md");
const outputPath = path.join(root, "src", "lib", "pdm-policy-rag-data.ts");

if (!fs.existsSync(sourcePath)) {
  console.error(`Policy source not found: ${sourcePath}`);
  process.exit(1);
}

const markdown = fs.readFileSync(sourcePath, "utf8");
const chunks = [];
let currentTitle = "";
let currentLines = [];

function flush() {
  const content = currentLines.join("\n").trim();
  if (!currentTitle || !content) return;
  chunks.push({
    id: currentTitle
      .toLowerCase()
      .replace(/[^\p{L}\p{N}]+/gu, "-")
      .replace(/^-|-$/g, ""),
    title: currentTitle,
    content
  });
}

for (const line of markdown.split(/\r?\n/)) {
  const heading = line.match(/^##\s+(.+)$/);
  if (heading) {
    flush();
    currentTitle = heading[1].trim();
    currentLines = [];
    continue;
  }
  if (currentTitle) currentLines.push(line);
}
flush();

const generated = [
  "// Generated by scripts/generate-policy-rag.mjs. Do not edit by hand.",
  "",
  "export type PdmPolicyChunk = {",
  "  id: string;",
  "  title: string;",
  "  content: string;",
  "};",
  "",
  `export const PDM_POLICY_SOURCE = ${JSON.stringify("docs/pdm-management-policy-draft.md")};`,
  "",
  `export const PDM_POLICY_CHUNKS: PdmPolicyChunk[] = ${JSON.stringify(chunks, null, 2)};`,
  ""
].join("\n");

fs.writeFileSync(outputPath, generated, "utf8");

console.log(JSON.stringify({
  source: path.relative(root, sourcePath).replaceAll(path.sep, "/"),
  output: path.relative(root, outputPath).replaceAll(path.sep, "/"),
  chunks: chunks.length
}, null, 2));
